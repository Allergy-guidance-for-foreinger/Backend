    CONSTRAINT fk_menu_review_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_menu_review_cafeteria
        FOREIGN KEY (cafeteria_id) REFERENCES cafeteria(id),
    CONSTRAINT fk_menu_review_menu
        FOREIGN KEY (menu_id) REFERENCES menu(id),
    CONSTRAINT fk_menu_review_meal_menu
        FOREIGN KEY (meal_menu_id) REFERENCES meal_menu(id)
);

CREATE TABLE menu_review_like (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL,
