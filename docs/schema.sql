CREATE TABLE menu_like (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    cafeteria_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_menu_like_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

    CONSTRAINT fk_menu_like_cafeteria
        FOREIGN KEY (cafeteria_id) REFERENCES cafeteria(id),

    CONSTRAINT fk_menu_like_menu
        FOREIGN KEY (menu_id) REFERENCES menu(id),

    CONSTRAINT uk_menu_like_user_target
        UNIQUE (user_id, cafeteria_id, menu_id)
);

CREATE TABLE menu_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    cafeteria_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    meal_menu_id BIGINT,
    meal_date DATE,
    content TEXT NOT NULL,
    like_count BIGINT NOT NULL DEFAULT 0,
    comment_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
