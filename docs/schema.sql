CREATE TABLE meal_menu_review_like (
    review_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,

    PRIMARY KEY (review_id, user_id),

    CONSTRAINT fk_meal_menu_review_like_review
        FOREIGN KEY (review_id) REFERENCES meal_menu_review(id) ON DELETE CASCADE,

    CONSTRAINT fk_meal_menu_review_like_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
